CREATE TABLE IF NOT EXISTS books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL CHECK (btrim(title) <> ''),
  author TEXT NOT NULL CHECK (btrim(author) <> ''),
  category TEXT NOT NULL CHECK (btrim(category) <> ''),
  total_copies INTEGER NOT NULL CHECK (total_copies >= 0),
  available_copies INTEGER NOT NULL CHECK (
    available_copies >= 0 AND available_copies <= total_copies
  )
);

CREATE TABLE IF NOT EXISTS members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL CHECK (btrim(full_name) <> ''),
  email TEXT NOT NULL CHECK (btrim(email) <> ''),
  join_date DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE UNIQUE INDEX IF NOT EXISTS members_email_lower_unique
  ON members (lower(email));

CREATE TABLE IF NOT EXISTS loans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
  borrow_date DATE NOT NULL DEFAULT CURRENT_DATE,
  due_date DATE NOT NULL CHECK (due_date > borrow_date),
  return_date DATE CHECK (return_date IS NULL OR return_date >= borrow_date)
);

CREATE INDEX IF NOT EXISTS loans_book_id_idx ON loans (book_id);
CREATE INDEX IF NOT EXISTS loans_member_id_idx ON loans (member_id);
CREATE INDEX IF NOT EXISTS loans_active_due_date_idx
  ON loans (due_date) WHERE return_date IS NULL;
